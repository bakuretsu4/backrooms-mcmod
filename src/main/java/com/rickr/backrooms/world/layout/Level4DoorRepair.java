package com.rickr.backrooms.world.layout;

import com.rickr.backrooms.Backrooms;
import com.rickr.backrooms.registry.ModAttachments;
import com.rickr.backrooms.registry.ModBlocks;
import com.rickr.backrooms.world.BackroomsLevel;
import com.rickr.backrooms.world.BackroomsSeeds;
import java.util.Arrays;
import java.util.concurrent.ConcurrentLinkedQueue;
import net.minecraft.core.BlockPos;
import net.minecraft.server.level.ServerLevel;
import net.minecraft.world.level.ChunkPos;
import net.minecraft.world.level.block.Block;
import net.minecraft.world.level.block.Blocks;
import net.minecraft.world.level.block.state.BlockState;
import net.minecraft.world.level.chunk.ChunkAccess;
import net.minecraft.world.level.chunk.LevelChunk;
import net.neoforged.bus.api.SubscribeEvent;
import net.neoforged.fml.common.EventBusSubscriber;
import net.neoforged.neoforge.event.level.ChunkEvent;
import net.neoforged.neoforge.event.tick.LevelTickEvent;

/**
 * A one-time repair for Level 4 chunks made by a broken build (c3f8e07), which built every room
 * door and opening as plain wall, so every room was sealed (and you could arrive inside one).
 *
 * <p>The first time such a chunk loads, every column where the current {@link Level4Plan} has a
 * door or doorway, and the world still has the broken build's wall there (skirting at floor + 1,
 * drywall at floor + 2), is rebuilt from the plan (the door with its frame head, or the opening):
 * only those columns, so nothing a player changed elsewhere is touched, and only columns the plan
 * builds (never the exit stairwell, its clearing, safe rooms or anomalous areas). Then the chunk is
 * marked ({@link ModAttachments#L4_DOOR_FIX}) and never checked again. Newly generated chunks are
 * already right: they are just marked.
 *
 * <p>Chunks are queued when they load and repaired on the server thread at the end of the next
 * level tick (the load event comes too early to touch the world), a few per tick. With nothing
 * queued it costs one empty-queue check per tick.
 */
@EventBusSubscriber(modid = Backrooms.MOD_ID)
public final class Level4DoorRepair {
    /** Bump to run a new repair over every chunk once more. */
    private static final int VERSION = 1;
    /** Chunks repaired per tick at most (each one is 256 plan lookups, a handful of block sets). */
    private static final int PER_TICK = 8;

    private static final ConcurrentLinkedQueue<Long> QUEUE = new ConcurrentLinkedQueue<>();

    @SubscribeEvent
    public static void onChunkLoad(ChunkEvent.Load event) {
        if (!(event.getLevel() instanceof ServerLevel level) || !isLevel4(level)) {
            return;
        }
        ChunkAccess chunk = event.getChunk();
        if (chunk.getData(ModAttachments.L4_DOOR_FIX) >= VERSION) {
            return;
        }
        if (event.isNewChunk()) {
            mark(chunk); // generated by this build: already right
            return;
        }
        QUEUE.add(chunk.getPos().toLong());
    }

    @SubscribeEvent
    public static void onLevelTick(LevelTickEvent.Post event) {
        if (QUEUE.isEmpty() || !(event.getLevel() instanceof ServerLevel level) || !isLevel4(level)) {
            return;
        }
        for (int i = 0; i < PER_TICK; i++) {
            Long pos = QUEUE.poll();
            if (pos == null) {
                return;
            }
            // Only a chunk that is still loaded (and fully loaded); an unloaded one is queued again
            // the next time it loads, since it isn't marked yet.
            LevelChunk chunk = level.getChunkSource().getChunkNow(ChunkPos.getX(pos), ChunkPos.getZ(pos));
            if (chunk != null && chunk.getData(ModAttachments.L4_DOOR_FIX) < VERSION) {
                repair(level, chunk);
                mark(chunk);
            }
        }
    }

    private static boolean isLevel4(ServerLevel level) {
        return BackroomsLevel.fromDimension(level.dimension()) == BackroomsLevel.LEVEL_4;
    }

    private static void mark(ChunkAccess chunk) {
        chunk.setData(ModAttachments.L4_DOOR_FIX, VERSION);
        chunk.setUnsaved(true);
    }

    /** Rebuilds the walled-up doors and openings of one chunk (see the class comment). */
    private static void repair(ServerLevel level, LevelChunk chunk) {
        Level4Layout layout = (Level4Layout) BackroomsLevel.LEVEL_4.layout();
        long seed = BackroomsSeeds.layoutSeed(level, BackroomsLevel.LEVEL_4);
        int floor = layout.floorY();
        int ceiling = layout.ceilingY();
        Block skirting = ModBlocks.OFFICE_WALL_BASE.get();
        Block drywall = ModBlocks.OFFICE_WALL.get();
        BlockPos.MutableBlockPos pos = new BlockPos.MutableBlockPos();
        int x0 = chunk.getPos().getMinBlockX();
        int z0 = chunk.getPos().getMinBlockZ();
        for (int dx = 0; dx < 16; dx++) {
            for (int dz = 0; dz < 16; dz++) {
                int x = x0 + dx;
                int z = z0 + dz;
                int kind = Level4Plan.kind(Level4Plan.column(seed, x, z));
                if (kind != Level4Plan.DOOR && kind != Level4Plan.DOORWAY) {
                    continue;
                }
                if (!chunk.getBlockState(pos.set(x, floor + 1, z)).is(skirting)
                        || !chunk.getBlockState(pos.set(x, floor + 2, z)).is(drywall)
                        || !layout.buildsFromPlan(seed, x, z)) {
                    continue; // not the broken build's wall (already right, or changed): leave it
                }
                // Clear the wall between floor and ceiling, then build the column as the plan does.
                BlockState[] column = new BlockState[ceiling - floor - 1];
                Arrays.fill(column, Blocks.AIR.defaultBlockState());
                layout.fillPlanColumn(seed, x, z, (y, state) -> {
                    if (y > floor && y < ceiling) {
                        column[y - floor - 1] = state;
                    }
                });
                for (int i = 0; i < column.length; i++) {
                    // Clients get the change; neighbours are not told (no shape updates that could
                    // pop the half-placed door while its other half is still wall).
                    level.setBlock(pos.set(x, floor + 1 + i, z), column[i], Block.UPDATE_CLIENTS | Block.UPDATE_KNOWN_SHAPE);
                }
            }
        }
    }

    private Level4DoorRepair() {}
}
