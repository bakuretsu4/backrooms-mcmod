package com.rickr.backrooms.world.layout;

import com.rickr.backrooms.Backrooms;
import com.rickr.backrooms.registry.ModAttachments;
import com.rickr.backrooms.world.BackroomsLevel;
import com.rickr.backrooms.world.BackroomsSeeds;
import java.util.Arrays;
import java.util.concurrent.ConcurrentLinkedQueue;
import net.minecraft.core.BlockPos;
import net.minecraft.server.level.ServerLevel;
import net.minecraft.world.level.ChunkPos;
import net.minecraft.world.level.block.Block;
import net.minecraft.world.level.block.Blocks;
import net.minecraft.world.level.block.state.BlockState;
import net.minecraft.world.level.chunk.ChunkAccess;
import net.minecraft.world.level.chunk.LevelChunk;
import net.neoforged.bus.api.SubscribeEvent;
import net.neoforged.fml.common.EventBusSubscriber;
import net.neoforged.neoforge.event.level.ChunkEvent;
import net.neoforged.neoforge.event.tick.LevelTickEvent;

/**
 * A one-time repair for Level 1 exit clearings generated before the clearing was cut out of the
 * corridor blocks: where an exit's clearing overlapped a corridor block, the block's walls, rooms
 * and crates were built right up to the stairwell, and could wall up its door for good.
 *
 * <p>Only the few chunks that touch an exit's clearing are looked at (at most nine per 384x384
 * region), and in them only the clearing columns inside a corridor block
 * ({@link Level1Layout#clearingInCorridorBlock}). There every block between the floor and the
 * ceiling that is still exactly what the old build put there is swapped for what the current build
 * puts there; anything a player placed, broke or opened is left as it is. (A supply crate in the
 * way is replaced too: its loot is only rolled when first opened, and anything put in it spills
 * out, as when it is broken.) Then the chunk is marked ({@link ModAttachments#L1_CLEARING_FIX}) and
 * never checked again. Newly generated chunks are already right: they are just marked.
 *
 * <p>Same scheduling as {@link Level4DoorRepair}: queued on load, repaired at the end of the next
 * level tick on the server thread, a few per tick.
 */
@EventBusSubscriber(modid = Backrooms.MOD_ID)
public final class Level1ClearingRepair {
    /** Bump to run a new repair over every clearing chunk once more. */
    private static final int VERSION = 1;
    private static final int PER_TICK = 4;

    private static final ConcurrentLinkedQueue<Long> QUEUE = new ConcurrentLinkedQueue<>();

    @SubscribeEvent
    public static void onChunkLoad(ChunkEvent.Load event) {
        if (!(event.getLevel() instanceof ServerLevel level) || !isLevel1(level)) {
            return;
        }
        ChunkAccess chunk = event.getChunk();
        ChunkPos pos = chunk.getPos();
        // Pure geometry, cheap: almost every chunk is nowhere near an exit and is never marked.
        if (!layout().chunkTouchesClearing(seed(level), pos.getMinBlockX(), pos.getMinBlockZ())
                || chunk.getData(ModAttachments.L1_CLEARING_FIX) >= VERSION) {
            return;
        }
        if (event.isNewChunk()) {
            mark(chunk); // generated by this build: already right
            return;
        }
        QUEUE.add(pos.toLong());
    }

    @SubscribeEvent
    public static void onLevelTick(LevelTickEvent.Post event) {
        if (QUEUE.isEmpty() || !(event.getLevel() instanceof ServerLevel level) || !isLevel1(level)) {
            return;
        }
        for (int i = 0; i < PER_TICK; i++) {
            Long pos = QUEUE.poll();
            if (pos == null) {
                return;
            }
            // Only a chunk that is still loaded; an unloaded one is queued again when it next loads.
            LevelChunk chunk = level.getChunkSource().getChunkNow(ChunkPos.getX(pos), ChunkPos.getZ(pos));
            if (chunk != null && chunk.getData(ModAttachments.L1_CLEARING_FIX) < VERSION) {
                repair(level, chunk);
                mark(chunk);
            }
        }
    }

    private static boolean isLevel1(ServerLevel level) {
        return BackroomsLevel.fromDimension(level.dimension()) == BackroomsLevel.LEVEL_1;
    }

    private static Level1Layout layout() {
        return (Level1Layout) BackroomsLevel.LEVEL_1.layout();
    }

    private static long seed(ServerLevel level) {
        return BackroomsSeeds.layoutSeed(level, BackroomsLevel.LEVEL_1);
    }

    private static void mark(ChunkAccess chunk) {
        chunk.setData(ModAttachments.L1_CLEARING_FIX, VERSION);
        chunk.setUnsaved(true);
    }

    /** Rebuilds the clearing columns of one chunk that the old build filled with corridor block. */
    private static void repair(ServerLevel level, LevelChunk chunk) {
        Level1Layout layout = layout();
        long seed = seed(level);
        int floor = layout.floorY();
        int ceiling = layout.ceilingY();
        BlockState air = Blocks.AIR.defaultBlockState();
        BlockState[] before = new BlockState[ceiling - floor + 1];
        BlockState[] now = new BlockState[ceiling - floor + 1];
        BlockPos.MutableBlockPos pos = new BlockPos.MutableBlockPos();
        int x0 = chunk.getPos().getMinBlockX();
        int z0 = chunk.getPos().getMinBlockZ();
        for (int dx = 0; dx < 16; dx++) {
            for (int dz = 0; dz < 16; dz++) {
                int x = x0 + dx;
                int z = z0 + dz;
                if (!layout.clearingInCorridorBlock(seed, x, z)) {
                    continue;
                }
                Arrays.fill(before, air);
                Arrays.fill(now, air);
                layout.fillCorridorBlock(seed, x, z, (y, state) -> {
                    if (y >= floor && y <= ceiling) {
                        before[y - floor] = state;
                    }
                });
                layout.fillColumn(seed, x, z, (y, state) -> {
                    if (y >= floor && y <= ceiling) {
                        now[y - floor] = state;
                    }
                });
                for (int i = 0; i < before.length; i++) {
                    pos.set(x, floor + i, z);
                    if (before[i] == now[i] || chunk.getBlockState(pos) != before[i]) {
                        continue; // unchanged, or not the old build's block any more: leave it
                    }
                    // Clients get the change; neighbours are not told (no shape updates that could
                    // pop half of a door while its other half is still being swapped).
                    level.setBlock(pos, now[i], Block.UPDATE_CLIENTS | Block.UPDATE_KNOWN_SHAPE);
                }
            }
        }
    }

    private Level1ClearingRepair() {}
}
