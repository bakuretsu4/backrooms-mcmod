package com.rickr.backrooms.block;

import net.minecraft.core.BlockPos;
import net.minecraft.util.StringRepresentable;
import net.minecraft.world.level.BlockGetter;
import net.minecraft.world.level.block.Block;
import net.minecraft.world.level.block.state.BlockState;
import net.minecraft.world.level.block.state.StateDefinition;
import net.minecraft.world.level.block.state.properties.BooleanProperty;
import net.minecraft.world.level.block.state.properties.EnumProperty;
import net.minecraft.world.level.block.state.properties.IntegerProperty;
import net.minecraft.world.phys.shapes.CollisionContext;
import net.minecraft.world.phys.shapes.Shapes;
import net.minecraft.world.phys.shapes.VoxelShape;

/**
 * A piece of a Level 39 bare tree: trunk, limb, branch or twig. Every piece is a round wooden
 * rod through the block's centre, joined to the piece it grows from (DOWN) and to the pieces
 * growing out of it (UP_*). Joins go straight up/down through the top/bottom face, or diagonally
 * at 45 degrees through the middle of a top/bottom edge, so a limb can climb outward one block
 * across for every block up. That is what makes the trees look grown instead of built from
 * crosses: a trunk that tapers (THICK 3 trunk, 2 limb, 1 branch, 0 twig) and forks into crooked
 * limbs leaning out in every direction.
 *
 * <p>The parent of a piece with DOWN = NORTH sits one block down and one block north, and has
 * UP_S set (its top-south edge is where they meet). The models are generated by
 * tools/anomaly_assets/level39_props.py as a multipart blockstate.
 */
public class TreeBlock extends Block {
    /** Where a piece joins the piece below it. */
    public enum Link implements StringRepresentable {
        NONE("none"), CENTER("center"), NORTH("north"), EAST("east"), SOUTH("south"), WEST("west");

        private final String name;

        Link(String name) {
            this.name = name;
        }

        @Override
        public String getSerializedName() {
            return name;
        }
    }

    public static final IntegerProperty THICK = IntegerProperty.create("thick", 0, 3);
    public static final EnumProperty<Link> DOWN = EnumProperty.create("down", Link.class);
    public static final BooleanProperty UP_C = BooleanProperty.create("up_c");
    public static final BooleanProperty UP_N = BooleanProperty.create("up_n");
    public static final BooleanProperty UP_E = BooleanProperty.create("up_e");
    public static final BooleanProperty UP_S = BooleanProperty.create("up_s");
    public static final BooleanProperty UP_W = BooleanProperty.create("up_w");

    /** Half widths (pixels) of the rod for each THICK. */
    private static final double[] HALF = {0.75, 1.25, 2.0, 3.0};
    private static final VoxelShape[] SHAPES = new VoxelShape[4];

    static {
        for (int t = 0; t < 4; t++) {
            SHAPES[t] = Block.box(8 - HALF[t], 0, 8 - HALF[t], 8 + HALF[t], 16, 8 + HALF[t]);
        }
    }

    public TreeBlock(Properties properties) {
        super(properties);
        registerDefaultState(stateDefinition.any().setValue(THICK, 3).setValue(DOWN, Link.CENTER)
                .setValue(UP_C, true).setValue(UP_N, false).setValue(UP_E, false).setValue(UP_S, false).setValue(UP_W, false));
    }

    @Override
    protected void createBlockStateDefinition(StateDefinition.Builder<Block, BlockState> builder) {
        builder.add(THICK, DOWN, UP_C, UP_N, UP_E, UP_S, UP_W);
    }

    @Override
    protected VoxelShape getShape(BlockState state, BlockGetter level, BlockPos pos, CollisionContext context) {
        return SHAPES[state.getValue(THICK)];
    }

    /** Only trunks and big limbs stop you; branches and twigs you push through. */
    @Override
    protected VoxelShape getCollisionShape(BlockState state, BlockGetter level, BlockPos pos, CollisionContext context) {
        return state.getValue(THICK) >= 2 ? SHAPES[state.getValue(THICK)] : Shapes.empty();
    }
}
