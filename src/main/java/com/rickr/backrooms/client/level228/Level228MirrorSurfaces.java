import org.jetbrains.annotations.Nullable;
import org.joml.Matrix4fStack;

/**
 * The surfaces of Level 228's mirrors and glass panels (spec 4.1), drawn every frame over every
 * pane near you, after the world and the stand-ins (AFTER_TRANSLUCENT_BLOCKS).
 *
 * <p>A pane is mostly see-through: what shows "in" it is the real twin room or sealed image volume
 * behind it (world/layout/Level228Plan) with its stand-ins (Level228Reflections). The surface adds
 * only what old silvered glass adds: a faint neutral veil, dust, smears and handprints,
 * desilvering creeping in from the edges, foxing, cracks catching the light, shattered panes'
 * missing shards down to the black backing, the funhouse panes' dark warped chrome; clear glass
 * its smudges. The look per pane comes from the Mirror record (surface, noise) so every viewer and
 * every reflected copy sees the same pane. Tiles are in textures/level228/mirror.png (generated by
 * tools/level_assets/level228_parts/mirror.py; the layout below must match it).
 *
 * <p>Seen at a slant a real mirror reads darker and glassier: each vertex gets a darkening
 * underlay and a stronger veil the more grazing the view (a cheap stand-in for Fresnel), worked out
 * per frame from the view direction. The type writes no depth (Level228PropRenderTypes#surface),
 * so the reflection keeps its true depth for fog and lights; quads are sorted back to front by the
 * buffer.
 *
 * <p>In the maze rooms a pane runs from column centre to column centre (the columns hide its
 * ends, as in the real mazes); elsewhere (chamber, foyer, hall) it fills its frame exactly.
 */
@EventBusSubscriber(modid = Backrooms.MOD_ID, value = Dist.CLIENT)
public final class Level228MirrorSurfaces {
    static final ResourceLocation TEXTURE = Backrooms.id("textures/level228/mirror.png");
    private static final int MAX_MIRRORS = 256;
    private static final double RADIUS = 40.0;

    // Tile layout of mirror.png (1024 x 1024 as shipped; painted at 2048): 4 x 4 tiles of 256 x 240
    // from the top left, in this order; a white patch at (0, 964) 32 x 32 for the darkening
    // underlay. Kept as fractions of the sheet, so the sheet's size can change freely.
    private static final int T_CLEAN = 0, T_TARNISH = 3, T_CRACK = 6, T_SHATTER = 9, T_CONCAVE = 11, T_CONVEX = 12,
            T_WAVE = 13, T_GLASS = 14;
    private static final float TILE_W = 256.0f / 1024.0f;
    private static final float TILE_H = 240.0f / 1024.0f;
    private static final float WHITE_U = 16.0f / 1024.0f;
    private static final float WHITE_V = 980.0f / 1024.0f;
    /** Where the column shafts hide the glass: the tiles' visible edge is this far in from each end. */
    private static final float EDGE_U = 0.2f / 3.0f;

    private static final Level228Plan.Mirror[] MIRRORS = new Level228Plan.Mirror[MAX_MIRRORS];
    private static int mirrorN;
    /** Per mirror, light on each side at three points along the span: block, sky (x2 sides x3). */
    private static final float[] LIGHT = new float[MAX_MIRRORS * 12];
    private static final BlockPos.MutableBlockPos POS = new BlockPos.MutableBlockPos();

    @Nullable
    private static RenderType type;
    @Nullable
    private static RenderType[] glassTypes;
    private static boolean registered;

    static {
        for (int i = 0; i < MAX_MIRRORS; i++) {
            MIRRORS[i] = new Level228Plan.Mirror();
        }
    }

    private Level228MirrorSurfaces() {}

    static void release() {
        if (registered) {
            Minecraft.getInstance().getTextureManager().release(TEXTURE);
            registered = false;
            type = null;
            glassTypes = null;
        }
        mirrorN = 0;
    }

    private static void ensureRegistered() {
        ResourceLocation[] sheets = Level228Props.sheets();
        if (registered && glassTypes != null && glassTypes.length == sheets.length) {
            return;
        }
        if (!registered) {
            Minecraft.getInstance().getTextureManager().register(TEXTURE, new Level228PropTexture(TEXTURE));
            type = Level228PropRenderTypes.surface(TEXTURE);
            registered = true;
        }
        glassTypes = new RenderType[sheets.length];
        for (int i = 0; i < sheets.length; i++) {
            glassTypes[i] = Level228PropRenderTypes.surface(sheets[i]);
        }
    }

    /** The mirrors near you, and their light, refreshed every tick (not every frame). */
    @SubscribeEvent
    public static void onClientTick(ClientTickEvent.Post event) {
        Minecraft mc = Minecraft.getInstance();
        ClientLevel level = mc.level;
        if (level == null || !Level228ClientState.inLevel228() || !Level228ClientState.hasSeed()) {
            mirrorN = 0;
            return;
        }
        Vec3 cam = mc.gameRenderer.getMainCamera().getPosition();
        mirrorN = Math.min(MAX_MIRRORS, Level228Plan.mirrorsNear(Level228ClientState.seed(), Level228ClientState.shift(),
                cam.x, cam.z, RADIUS, MIRRORS));
        for (int i = 0; i < mirrorN; i++) {
            Level228Plan.Mirror m = MIRRORS[i];
            double y = (m.y0 + m.y1) * 0.5;
            for (int side = 0; side < 2; side++) {
                double off = side == 0 ? -0.5 : 0.5;
                for (int k = 0; k < 3; k++) {
                    double a = m.min + (m.max - m.min) * (0.15 + 0.35 * k);
                    if (m.axis == 0) {
                        POS.set((int) Math.floor(m.plane + off), (int) Math.floor(y), (int) Math.floor(a));
                    } else {
                        POS.set((int) Math.floor(a), (int) Math.floor(y), (int) Math.floor(m.plane + off));
                    }
                    int o = i * 12 + side * 6 + k * 2;
                    LIGHT[o] = level.getBrightness(LightLayer.BLOCK, POS);
                    LIGHT[o + 1] = level.getBrightness(LightLayer.SKY, POS);
                }
            }
        }
    }

    @SubscribeEvent
    public static void onRenderStage(RenderLevelStageEvent event) {
        if (event.getStage() != RenderLevelStageEvent.Stage.AFTER_TRANSLUCENT_BLOCKS) {
            return;
        }
        Minecraft mc = Minecraft.getInstance();
        ClientLevel level = mc.level;
        if (level == null || !Level228ClientState.inLevel228() || Level228Iris.shadowPass() || !Level228PropMeshes.isLoaded()) {
            return;
        }
        ensureRegistered();
        RenderType t = type;
        if (t == null) {
            return;
        }
        Vec3 cam = event.getCamera().getPosition();
        FrustumInvoker frustum = (FrustumInvoker) event.getFrustum();
        Matrix4fStack modelView = RenderSystem.getModelViewStack();
        modelView.pushMatrix();
        modelView.set(event.getModelViewMatrix());
        RenderSystem.applyModelViewMatrix();
        MultiBufferSource.BufferSource buffers = mc.renderBuffers().bufferSource();
        VertexConsumer out = null;
        for (int i = 0; i < mirrorN; i++) {
            Level228Plan.Mirror m = MIRRORS[i];
            boolean maze = maze(m.zone);
            double a0 = maze ? m.min - 0.5 : m.min;
            double a1 = maze ? m.max + 0.5 : m.max;
            if (!visible(frustum, m.axis, m.plane, a0, a1, m.y0, m.y1)) {
                continue;
            }
            if (out == null) {
                out = buffers.getBuffer(t);
            }
            int tile = tile(m.surface, m.noise);
            float u0 = maze ? 0.0f : EDGE_U;
            float u1 = maze ? 1.0f : 1.0f - EDGE_U;
            pane(out, cam, m.axis, m.plane, a0, a1, m.y0, m.y1, tile, u0, u1, i, distorting(m.surface));
        }
        // Clear glass panels (the Glass Labyrinth), from the props.
        for (int c = 0; c < Level228Props.drawnCount; c++) {
            Level228Props.Chunk ch = Level228Props.drawn[c];
            for (int p = 0; p < ch.paneN; p++) {
                int axis = (int) ch.pane[p * 6];
                float plane = ch.pane[p * 6 + 1];
                float a0 = ch.pane[p * 6 + 2];
                float a1 = ch.pane[p * 6 + 3];
                float y0 = ch.pane[p * 6 + 4];
                float y1 = ch.pane[p * 6 + 5];
                if (!visible(frustum, axis, plane, a0, a1, y0, y1)) {
                    continue;
                }
                if (out == null) {
                    out = buffers.getBuffer(t);
                }
                pane(out, cam, axis, plane, a0, a1, y0, y1, T_GLASS + Math.floorMod(ch.paneNoise[p], 2), 0.0f, 1.0f, -1, false);
            }
        }
        if (out != null) {
            buffers.endBatch(t);
        }
        drawGlassProps(buffers, cam);
        modelView.popMatrix();
        RenderSystem.applyModelViewMatrix();
    }

    private static boolean maze(Zone z) {
        return z == Zone.CRYSTAL || z == Zone.ALHAMBRA || z == Zone.FUNHOUSE || z == Zone.GLASS;
    }

    private static boolean distorting(int surface) {
        return surface == Level228Plan.S_DISTORT_CONCAVE || surface == Level228Plan.S_DISTORT_CONVEX
                || surface == Level228Plan.S_DISTORT_WAVE;
    }

    private static int tile(int surface, int noise) {
        return switch (surface) {
            case Level228Plan.S_TARNISHED -> T_TARNISH + Math.floorMod(noise, 3);
            case Level228Plan.S_CRACKED -> T_CRACK + Math.floorMod(noise, 3);
            case Level228Plan.S_SHATTERED -> T_SHATTER + Math.floorMod(noise, 2);
            case Level228Plan.S_DISTORT_CONCAVE -> T_CONCAVE;
            case Level228Plan.S_DISTORT_CONVEX -> T_CONVEX;
            case Level228Plan.S_DISTORT_WAVE -> T_WAVE;
            default -> T_CLEAN + Math.floorMod(noise, 3);
        };
    }

    private static boolean visible(FrustumInvoker f, int axis, double plane, double a0, double a1, double y0, double y1) {
        return axis == 0
                ? f.backrooms$cubeInFrustum(plane - 0.05, y0, a0, plane + 0.05, y1, a1)
                : f.backrooms$cubeInFrustum(a0, y0, plane - 0.05, a1, y1, plane + 0.05);
    }

    /**
     * One pane: a darkening underlay (white texel tinted black, alpha rising at grazing angles)
     * and the surface tile over it, both cut into a grid so the angle and the light can vary
     * across it.
     */
    private static void pane(VertexConsumer out, Vec3 cam, int axis, double plane, double a0, double a1, double y0, double y1,
                             int tile, float u0, float u1, int lightIndex, boolean distort) {
        int cols = Math.max(2, (int) Math.ceil((a1 - a0) * 1.5));
        int rows = Math.max(2, (int) Math.ceil((y1 - y0) * 1.2));
        float tu = (tile % 4) * TILE_W;
        float tv = (tile / 4) * TILE_H;
        // Which side the camera is on (light is taken on that side); the underlay is pushed a
        // hair away from the camera so the buffer's back-to-front sort draws it first.
        double side = (axis == 0 ? cam.x : cam.z) - plane;
        float push = side > 0 ? -0.004f : 0.004f;
        int lightSide = side > 0 ? 1 : 0;
        int fixedLight = lightIndex < 0 ? cameraLight(cam, (y0 + y1) * 0.5) : -1;
        for (int layer = 0; layer < 2; layer++) {
            for (int c = 0; c < cols; c++) {
                for (int r = 0; r < rows; r++) {
                    vertex(out, cam, axis, plane, a0, a1, y0, y1, c, r, cols, rows, tu, tv, u0, u1, layer, push, lightIndex,
                            lightSide, fixedLight, distort);
                    vertex(out, cam, axis, plane, a0, a1, y0, y1, c + 1, r, cols, rows, tu, tv, u0, u1, layer, push, lightIndex,
                            lightSide, fixedLight, distort);
                    vertex(out, cam, axis, plane, a0, a1, y0, y1, c + 1, r + 1, cols, rows, tu, tv, u0, u1, layer, push,
                            lightIndex, lightSide, fixedLight, distort);
                    vertex(out, cam, axis, plane, a0, a1, y0, y1, c, r + 1, cols, rows, tu, tv, u0, u1, layer, push, lightIndex,
                            lightSide, fixedLight, distort);
                }
            }
        }
    }

    private static void vertex(VertexConsumer out, Vec3 cam, int axis, double plane, double a0, double a1, double y0, double y1,
                               int c, int r, int cols, int rows, float tu, float tv, float u0, float u1, int layer, float push,
                               int lightIndex, int lightSide, int fixedLight, boolean distort) {
        float s = c / (float) cols;
        float t = r / (float) rows;
        double a = a0 + (a1 - a0) * s;
        double y = y0 + (y1 - y0) * t;
        double p = plane + (layer == 0 ? push : 0.0);
        double wx = axis == 0 ? p : a;
        double wz = axis == 0 ? a : p;
        float x = (float) (wx - cam.x);
        float yy = (float) (y - cam.y);
        float z = (float) (wz - cam.z);
        float len = (float) Math.sqrt(x * x + yy * yy + z * z) + 1.0e-4f;
        float cos = Math.abs((axis == 0 ? x : z) / len);
        float graze = 1.0f - cos;
        int light = fixedLight >= 0 ? fixedLight : light(lightIndex, lightSide, s);
        float nx = axis == 0 ? 1.0f : 0.0f;
        float nz = axis == 0 ? 0.0f : 1.0f;
        int colour;
        float u;
        float v;
        if (layer == 0) {
            // Darker the more grazing: a mirror seen edge-on shows more of its glass than its image.
            float alpha = (distort ? 0.10f : 0.04f) + 0.42f * graze * graze;
            colour = Level228Props.packColour(0.0f, 0.0f, 0.0f, alpha);
            u = WHITE_U;
            v = WHITE_V;
        } else {
            // The tile keeps its own alpha (vertex colour can only scale it down); the stronger
            // look of glass at a slant comes from the underlay. Head-on the veil is a touch
            // brighter than edge-on.
            float lum = 0.82f + 0.18f * cos;
            colour = Level228Props.packColour(lum, lum, lum, 1.0f);
            u = tu + (u0 + (u1 - u0) * s) * TILE_W;
            v = tv + (1.0f - t) * TILE_H;
        }
        out.addVertex(x, yy, z, colour, u, v, OverlayTexture.NO_OVERLAY, light, nx, 0.0f, nz);
    }

    /** Light where the camera stands (clear glass panes: you are always near the one you see). */
    private static int cameraLight(Vec3 cam, double y) {
        ClientLevel level = Minecraft.getInstance().level;
        if (level == null) {
            return 0;
        }
        POS.set((int) Math.floor(cam.x), (int) Math.floor(y), (int) Math.floor(cam.z));
        return level.getBrightness(LightLayer.BLOCK, POS) << 4 | level.getBrightness(LightLayer.SKY, POS) << 20;
    }

    /** A mirror's light at fraction s of its span on the given side, from the tick's three samples. */
    private static int light(int index, int side, float s) {
        float f = Math.min(2.0f, Math.max(0.0f, (s - 0.15f) / 0.35f));
        int k = Math.min(1, (int) f);
        float w = f - k;
        int o = index * 12 + side * 6;
        float b = LIGHT[o + k * 2] * (1 - w) + LIGHT[o + (k + 1) * 2] * w;
        float sk = LIGHT[o + k * 2 + 1] * (1 - w) + LIGHT[o + (k + 1) * 2 + 1] * w;
        return Math.min(240, Math.round(b * 16.0f)) | Math.min(240, Math.round(sk * 16.0f)) << 16;
    }

    /** See-through props (the ticket booth's window), in their own sheets. */
    private static void drawGlassProps(MultiBufferSource.BufferSource buffers, Vec3 cam) {
        RenderType[] types = glassTypes;
        if (types == null) {
            return;
        }
        float cx = (float) cam.x;
        float cy = (float) cam.y;
        float cz = (float) cam.z;
        for (int s = 0; s < types.length; s++) {
            VertexConsumer out = null;
            for (int c = 0; c < Level228Props.drawnCount; c++) {
                Level228Props.Chunk ch = Level228Props.drawn[c];
                for (int v = 0; v < ch.glassN; v++) {
                    if (ch.glassSheet[v] != s) {
                        continue;
                    }
                    if (out == null) {
                        out = buffers.getBuffer(types[s]);
                    }
                    int o = v * 9;
                    int sh = (int) (ch.glass[o + 8] * 255.0f);
                    out.addVertex(ch.glass[o] - cx, ch.glass[o + 1] - cy, ch.glass[o + 2] - cz, 0xFF000000 | sh << 16 | sh << 8 | sh,
                            ch.glass[o + 3], ch.glass[o + 4], OverlayTexture.NO_OVERLAY, ch.glassLight[v], ch.glass[o + 5],
                            ch.glass[o + 6], ch.glass[o + 7]);
                }
            }
            if (out != null) {
                buffers.endBatch(types[s]);
            }
        }
    }
}
