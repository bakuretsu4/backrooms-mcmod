import org.slf4j.LoggerFactory;

/**
 * Draws the pool water of the Poolrooms and Level 37 (vanilla's water faces are switched off
 * there, see {@link VanillaWaterHider}).
 *
 * <p><b>When:</b> right after the whole level has been drawn AND lit. Veil adds its dynamic lights
 * onto the picture at the very end of {@code LevelRenderer.renderLevel}, and NeoForge's
 * {@code AFTER_LEVEL} stage fires right after that method returns, so at that moment the screen
 * holds the finished, lit room (minus the water). The camcorder post effect runs later still,
 * so it films our water like everything else (NightShot included).
 *
 * <p><b>How:</b>
 * <ol>
 *   <li>Copy the screen's colour and depth into our own buffer ({@link #scene}) and build a few
 *       blurred sizes of the colour (mipmaps) for soft lookups.</li>
 *   <li>Draw the surface quads from {@link WaterSurfaces} with the {@code pool_water} shader. For
 *       each water pixel it looks at the copy: the floor behind it (wobbled by the ripples),
 *       how much water lies in between (more water = deeper colour), moving light patterns on
 *       that floor, a reflection traced across the depth buffer, and sun sparkles.</li>
 *   <li>With your eyes under water, one more full-screen pass ({@code pool_underwater}) adds
 *       the light patterns on the pool walls/floor around you and soft light shafts.</li>
 * </ol>
 * Both shaders are vanilla-style core shaders (assets/backrooms/shaders/core/).
 */
@EventBusSubscriber(modid = Backrooms.MOD_ID, value = Dist.CLIENT)
public final class WaterRenderer {
    private static final Logger LOGGER = LoggerFactory.getLogger("backrooms/water");
    /** Tileable ripple normal map and caustic pattern (generated by tools/gen_assets.py, tex_water_*). */
    private static final ResourceLocation RIPPLES = Backrooms.id("textures/water/ripples.png");
    private static final ResourceLocation CAUSTICS = Backrooms.id("textures/water/caustics.png");
    /** Noise coordinates wrap every 4096 blocks (every texture tiling divides it), so floats stay precise. */
    private static final double WRAP = 4096.0;
    /** Light shafts under water (0 = none). */
    private static final float SHAFT_STRENGTH = 1.0f;

    @Nullable
    private static ShaderInstance surfaceShader;
    @Nullable
    private static ShaderInstance underwaterShader;
    /** The water style of the level we draw in, or null = draw nothing this tick. */
    @Nullable
    private static WaterStyle style;

    /** Copy of the lit scene (colour with mipmaps + depth). */
    @Nullable
    private static TextureTarget scene;
    @Nullable
    private static Integer sceneDepthId;
    @Nullable
    private static VertexBuffer mesh;
    private static boolean meshEmpty = true;
    private static int meshRevision = Integer.MIN_VALUE;
    private static int originX;
    private static int originY;
    private static int originZ;
    @Nullable
    private static ByteBufferBuilder meshBytes;
    @Nullable
    private static VertexBuffer screenQuad;

    // Terrain fog of this frame, captured while the level draws (vanilla turns fog off at the end).
    private static float fogStart = Float.MAX_VALUE;
    private static float fogEnd = Float.MAX_VALUE;
    private static int fogShape;
    private static final float[] FOG_COLOR = new float[4];

    private static final Matrix4f INV_PROJECTION = new Matrix4f();

    /** Mod bus: load our two shaders. A broken shader only logs an error and leaves vanilla water on. */
    @SubscribeEvent
    public static void onRegisterShaders(RegisterShadersEvent event) {
        surfaceShader = null;
        underwaterShader = null;
        try {
            event.registerShader(new ShaderInstance(event.getResourceProvider(), Backrooms.id("pool_water"),
                    DefaultVertexFormat.POSITION), shader -> surfaceShader = shader);
            event.registerShader(new ShaderInstance(event.getResourceProvider(), Backrooms.id("pool_underwater"),
                    DefaultVertexFormat.POSITION), shader -> underwaterShader = shader);
        } catch (Exception e) {
            LOGGER.error("[{}] Pool water shaders failed to load; vanilla water stays on", Backrooms.MOD_ID, e);
        }
    }

    /** The water style being drawn right now, or null. */
    @Nullable
    static WaterStyle activeStyle() {
        return style;
    }

    @SubscribeEvent
    public static void onClientTick(ClientTickEvent.Post event) {
        Minecraft mc = Minecraft.getInstance();
        WaterStyle levelStyle = mc.level == null ? null : WaterStyle.forLevel(BackroomsLevel.fromDimension(mc.level.dimension()));
        boolean available = surfaceShader != null && underwaterShader != null
                && (levelStyle == null || !VanillaWaterHider.shaderPackInUse());
        VanillaWaterHider.setRendererAvailable(available);
        style = available ? levelStyle : null;
        WaterSurfaces.tick(mc, style != null);
        if (style == null && scene != null) {
            freeGpu(); // left the pool levels: give the screen-sized copy back
        }
    }

    @SubscribeEvent(priority = EventPriority.HIGH) // before the camcorder copies the depth (ClientEvents)
    public static void onRenderStage(RenderLevelStageEvent event) {
        if (style == null) {
            return;
        }
        if (event.getStage() == RenderLevelStageEvent.Stage.AFTER_SOLID_BLOCKS) {
            captureFog();
        } else if (event.getStage() == RenderLevelStageEvent.Stage.AFTER_LEVEL) {
            draw(event);
        }
    }

    private static void captureFog() {
        fogStart = RenderSystem.getShaderFogStart();
        fogEnd = RenderSystem.getShaderFogEnd();
        fogShape = RenderSystem.getShaderFogShape().getIndex();
        System.arraycopy(RenderSystem.getShaderFogColor(), 0, FOG_COLOR, 0, 4);
    }

    private static void draw(RenderLevelStageEvent event) {
        Minecraft mc = Minecraft.getInstance();
        ShaderInstance surface = surfaceShader;
        ShaderInstance underwater = underwaterShader;
        WaterStyle look = style;
        if (surface == null || underwater == null || look == null || mc.level == null) {
            return;
        }
        Camera camera = event.getCamera();
        Vec3 eye = camera.getPosition();
        rebuildMeshIfNeeded(eye);
        boolean eyeInWater = UnderwaterView.cameraInWater();
        if (meshEmpty && !eyeInWater) {
            return;
        }

        RenderTarget main = mc.getMainRenderTarget();
        copyScene(main);
        main.bindWrite(false);

        Matrix4f view = event.getModelViewMatrix();
        Matrix4f projection = event.getProjectionMatrix();
        INV_PROJECTION.set(projection).invert();
        float seconds = (float) ((System.nanoTime() / 1.0e9) % 3600.0);
        float lowX = (float) (eye.x - Math.floor(eye.x / WRAP) * WRAP);
        float lowY = (float) (eye.y - Math.floor(eye.y / WRAP) * WRAP);
        float lowZ = (float) (eye.z - Math.floor(eye.z / WRAP) * WRAP);
        AbstractTexture ripples = mc.getTextureManager().getTexture(RIPPLES);
        AbstractTexture caustics = mc.getTextureManager().getTexture(CAUSTICS);

        if (!meshEmpty && mesh != null) {
            surface.setSampler("SceneColor", scene);
            surface.setSampler("SceneDepth", sceneDepthId);
            surface.setSampler("Ripples", ripples);
            surface.setSampler("Caustics", caustics);
            set(surface, "InvProjMat").set(INV_PROJECTION);
            set(surface, "MeshOffset").set((float) (originX - eye.x), (float) (originY - eye.y), (float) (originZ - eye.z));
            set(surface, "CameraLow").set(lowX, lowY, lowZ);
            set(surface, "Time").set(seconds);
            set(surface, "ShallowColor").set(WaterStyle.red(look.shallowColor()), WaterStyle.green(look.shallowColor()),
                    WaterStyle.blue(look.shallowColor()), look.shallowAlpha());
            set(surface, "DeepColor").set(WaterStyle.red(look.deepColor()), WaterStyle.green(look.deepColor()),
                    WaterStyle.blue(look.deepColor()), look.deepAlpha());
            set(surface, "DeepDistance").set(look.deepDistance());
            set(surface, "ReflectColor").set(WaterStyle.red(look.reflectColor()), WaterStyle.green(look.reflectColor()),
                    WaterStyle.blue(look.reflectColor()));
            set(surface, "CausticStrength").set(look.causticStrength());
            set(surface, "RippleStrength").set(look.rippleStrength());
            set(surface, "Refraction").set(look.refraction());
            set(surface, "SunDir").set(look.sunDir().x(), look.sunDir().y(), look.sunDir().z());
            set(surface, "SunColor").set(WaterStyle.red(look.sunColor()), WaterStyle.green(look.sunColor()),
                    WaterStyle.blue(look.sunColor()));
            set(surface, "SunGlints").set(look.sunGlints());
            set(surface, "ClearDepth").set(look.clearDepth());
            set(surface, "TintStrength").set(look.tintStrength());
            set(surface, "WaterBrightness").set(look.brightness());
            setFog(surface);

            RenderSystem.enableDepthTest();
            RenderSystem.depthFunc(GL11.GL_LEQUAL);
            RenderSystem.depthMask(true);
            RenderSystem.disableBlend();
            RenderSystem.disableCull(); // seen from below too, when you swim under it
            mesh.bind();
            mesh.drawWithShader(view, projection, surface);
            VertexBuffer.unbind();
            RenderSystem.enableCull();
        }

        if (eyeInWater && screenQuad != null) {
            underwater.setSampler("SceneColor", scene);
            underwater.setSampler("SceneDepth", sceneDepthId);
            underwater.setSampler("Ripples", ripples);
            underwater.setSampler("Caustics", caustics);
            set(underwater, "InvProjMat").set(INV_PROJECTION);
            set(underwater, "CameraLow").set(lowX, lowY, lowZ);
            set(underwater, "Time").set(seconds);
            set(underwater, "WaterLevel").set((float) (UnderwaterView.surfaceAbove(mc.level, eye) - eye.y));
            set(underwater, "SunDir").set(look.sunDir().x(), look.sunDir().y(), look.sunDir().z());
            set(underwater, "SunColor").set(WaterStyle.red(look.sunColor()), WaterStyle.green(look.sunColor()),
                    WaterStyle.blue(look.sunColor()));
            set(underwater, "ShallowColor").set(WaterStyle.red(look.shallowColor()), WaterStyle.green(look.shallowColor()),
                    WaterStyle.blue(look.shallowColor()));
            set(underwater, "CausticStrength").set(look.causticStrength());
            set(underwater, "ShaftStrength").set(SHAFT_STRENGTH);

            RenderSystem.disableDepthTest();
            RenderSystem.depthMask(false);
            RenderSystem.enableBlend();
            RenderSystem.blendFunc(GlStateManager.SourceFactor.ONE, GlStateManager.DestFactor.ONE); // adds light
            screenQuad.bind();
            screenQuad.drawWithShader(view, projection, underwater);
            VertexBuffer.unbind();
            RenderSystem.disableBlend();
            RenderSystem.defaultBlendFunc();
            RenderSystem.depthMask(true);
            RenderSystem.enableDepthTest();
        }
    }

    private static AbstractUniform set(ShaderInstance shader, String name) {
        return shader.safeGetUniform(name);
    }

    private static void setFog(ShaderInstance shader) {
        set(shader, "SceneFogStart").set(fogStart);
        set(shader, "SceneFogEnd").set(fogEnd);
        set(shader, "SceneFogColor").set(FOG_COLOR[0], FOG_COLOR[1], FOG_COLOR[2], FOG_COLOR[3]);
        set(shader, "SceneFogShape").set(fogShape);
    }

    /**
     * Copies the finished picture (colour + depth) into {@link #scene}: we can't read the screen
     * while drawing onto it. Colour and depth are copied separately so a depth format mismatch
     * (stencil) can never stop the colour copy.
     */
    private static void copyScene(RenderTarget main) {
        if (scene == null) {
            scene = new TextureTarget(main.width, main.height, true, Minecraft.ON_OSX);
            if (main.isStencilEnabled()) {
                scene.enableStencil(); // the depth formats must match for the copy
            }
            afterSceneCreated();
        } else if (scene.width != main.width || scene.height != main.height) {
            scene.resize(main.width, main.height, Minecraft.ON_OSX);
            afterSceneCreated();
        }
        GlStateManager._glBindFramebuffer(GL30.GL_READ_FRAMEBUFFER, main.frameBufferId);
        GlStateManager._glBindFramebuffer(GL30.GL_DRAW_FRAMEBUFFER, scene.frameBufferId);
        GlStateManager._glBlitFrameBuffer(0, 0, main.width, main.height, 0, 0, scene.width, scene.height,
                GL11.GL_COLOR_BUFFER_BIT, GL11.GL_NEAREST);
        scene.copyDepthFrom(main);
        // Blurred sizes of the picture (each half the size of the last) for soft, cheap lookups.
        GlStateManager._bindTexture(scene.getColorTextureId());
        GL30.glGenerateMipmap(GL11.GL_TEXTURE_2D);
        GlStateManager._bindTexture(0);
    }

    /** (Re)created copy: linear + mipmapped colour sampling, clamped at the screen edges. */
    private static void afterSceneCreated() {
        GlStateManager._bindTexture(scene.getColorTextureId());
        GlStateManager._texParameter(GL11.GL_TEXTURE_2D, GL11.GL_TEXTURE_MIN_FILTER, GL11.GL_LINEAR_MIPMAP_LINEAR);
        GlStateManager._texParameter(GL11.GL_TEXTURE_2D, GL11.GL_TEXTURE_MAG_FILTER, GL11.GL_LINEAR);
        GlStateManager._texParameter(GL11.GL_TEXTURE_2D, GL11.GL_TEXTURE_WRAP_S, GL30.GL_CLAMP_TO_EDGE);
        GlStateManager._texParameter(GL11.GL_TEXTURE_2D, GL11.GL_TEXTURE_WRAP_T, GL30.GL_CLAMP_TO_EDGE);
        GlStateManager._bindTexture(0);
        sceneDepthId = scene.getDepthTextureId();
        if (screenQuad == null) {
            BufferBuilder quad = Tesselator.getInstance().begin(VertexFormat.Mode.QUADS, DefaultVertexFormat.POSITION);
            quad.addVertex(-1.0f, -1.0f, 0.0f);
            quad.addVertex(1.0f, -1.0f, 0.0f);
            quad.addVertex(1.0f, 1.0f, 0.0f);
            quad.addVertex(-1.0f, 1.0f, 0.0f);
            screenQuad = new VertexBuffer(VertexBuffer.Usage.STATIC);
            screenQuad.bind();
            screenQuad.upload(quad.buildOrThrow());
            VertexBuffer.unbind();
        }
    }

    /**
     * Uploads all surface quads again when {@link WaterSurfaces} reports a change (at most once
     * per tick, usually much rarer). Vertices are stored relative to the camera block at that
     * moment ({@link #originX}...), which keeps the float positions small and precise.
     */
    private static void rebuildMeshIfNeeded(Vec3 eye) {
        int revision = WaterSurfaces.revision();
        if (revision == meshRevision && mesh != null) {
            return;
        }
        meshRevision = revision;
        originX = Mth.floor(eye.x);
        originY = Mth.floor(eye.y);
        originZ = Mth.floor(eye.z);
        if (meshBytes == null) {
            meshBytes = new ByteBufferBuilder(64 * 1024);
        }
        if (mesh == null) {
            mesh = new VertexBuffer(VertexBuffer.Usage.DYNAMIC);
        }
        BufferBuilder builder = new BufferBuilder(meshBytes, VertexFormat.Mode.QUADS, DefaultVertexFormat.POSITION);
        for (int[] quads : WaterSurfaces.sections()) {
            for (int i = 0; i < quads.length; i += WaterSurfaces.INTS_PER_QUAD) {
                float x0 = quads[i] - originX;
                float z0 = quads[i + 1] - originZ;
                float x1 = quads[i + 2] - originX;
                float z1 = quads[i + 3] - originZ;
                float y = quads[i + 4] - originY + WaterSurfaces.height(quads[i + 5]);
                builder.addVertex(x0, y, z0);
                builder.addVertex(x0, y, z1);
                builder.addVertex(x1, y, z1);
                builder.addVertex(x1, y, z0);
            }
        }
        MeshData data = builder.build();
        meshEmpty = data == null;
        if (data != null) {
            mesh.bind();
            mesh.upload(data); // also frees the mesh data
            VertexBuffer.unbind();
        }
    }

    private static void freeGpu() {
        if (scene != null) {
            scene.destroyBuffers();
            scene = null;
            sceneDepthId = null;
        }
        if (mesh != null) {
            mesh.close();
            mesh = null;
        }
        meshEmpty = true;
        meshRevision = Integer.MIN_VALUE;
    }

    private WaterRenderer() {}
}
